#!/usr/bin/env Rscript
# Offline/read-only validation of a W00-to-W01 Shiny receipt contract.
suppressPackageStartupMessages(library(jsonlite))
args <- commandArgs(trailingOnly=TRUE)
arg <- function(k) {i<-match(k,args);if(is.na(i)||i==length(args))stop("Missing ",k,call.=FALSE);args[[i+1L]]}
p<-arg("--receipt");review<-arg("--review-id");run<-arg("--run-id")
if(!file.exists(p))stop("Missing W00 receipt",call.=FALSE)
x<-fromJSON(p,simplifyVector=FALSE)
req<-c("status","review_id","github_run_id","zenodo_record_id","visibility","sources","manifest_sha256")
if(length(setdiff(req,names(x))))stop("Missing W00 handoff receipt fields",call.=FALSE)
if(!identical(x$status,"published")||!identical(x$visibility,"restricted"))
  stop("W00 archive must be published and restricted",call.=FALSE)
if(!identical(as.character(x$review_id),review)||!identical(as.character(x$github_run_id),run))
  stop("W00 handoff review or run mismatch",call.=FALSE)
if(!grepl("^[0-9]+$",run)||!grepl("^[0-9]+$",as.character(x$zenodo_record_id)))
  stop("Invalid W00 run or Zenodo record ID",call.=FALSE)
src<-as.character(unlist(x$sources,use.names=FALSE))
if(!length(src)||anyDuplicated(src)||any(!grepl("^[a-z0-9][a-z0-9_-]*$",src)))
  stop("Invalid W00 source list",call.=FALSE)
hash<-as.character(x$manifest_sha256)
if(length(hash)!=1L||!grepl("^[a-fA-F0-9]{64}$",hash))
  stop("Invalid W00 archive manifest SHA256",call.=FALSE)
cat("PASS: Shiny W00 handoff receipt validated for review ",review," run ",run,"\n",sep="")
